"""Rasterize the UI font atlas for the frontend (development tool).

Renders printable ASCII and Latin-1 (U+00A0-U+00FF) from an OFL-licensed font (Inter SemiBold by default)
into a single-channel atlas, deflates it and writes frontend/assets/fe_font.h.
The atlas is a derivative of the font and stays under the SIL OFL 1.1
(LICENSES/Inter-OFL.txt).

usage: python tools/make_font.py [FONT.otf] [--size 44]
"""
from __future__ import annotations

import argparse
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("font", nargs="?", default="/usr/share/fonts/opentype/inter/Inter-SemiBold.otf")
    p.add_argument("--size", type=int, default=44)
    p.add_argument("--out", type=Path, default=ROOT / "frontend" / "assets" / "fe_font.h")
    a = p.parse_args()
    font = ImageFont.truetype(a.font, a.size)
    ascent, descent = font.getmetrics()
    line = ascent + descent
    chars = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(160, 256)]
    pad = 2
    width = 1024
    x = y = 0
    rows = []
    glyphs = []
    for ch in chars:
        left, top, right, bottom = font.getbbox(ch)
        adv = font.getlength(ch)
        gw = max(1, right - min(left, 0)) + pad * 2
        if x + gw > width:
            x = 0
            y += line + pad * 2
        glyphs.append((ch, x, y, gw, line + pad * 2, adv, min(left, 0)))
        x += gw
    height = y + line + pad * 2
    height = (height + 3) & ~3
    img = Image.new("L", (width, height), 0)
    d = ImageDraw.Draw(img)
    for ch, gx, gy, gw, gh, adv, left in glyphs:
        d.text((gx + pad - left, gy + pad), ch, font=font, fill=255)
    data = zlib.compress(img.tobytes(), 9)
    out = []
    out.append("/* Generated by tools/make_font.py - UI font atlas rasterized from Inter")
    out.append(" * (SIL Open Font License 1.1, see LICENSES/Inter-OFL.txt). */")
    out.append("#ifndef FE_FONT_DATA_H\n#define FE_FONT_DATA_H\n#include <stdint.h>")
    out.append(f"#define FE_FONT_ATLAS_W {width}\n#define FE_FONT_ATLAS_H {height}")
    out.append(f"#define FE_FONT_LINE {line + pad * 2}\n#define FE_FONT_ASCENT {ascent}\n#define FE_FONT_PX {a.size}")
    out.append("typedef struct fe_glyph_def { int16_t x, y, w, h; float advance; int16_t left; } fe_glyph_def;")
    out.append(f"#define FE_FONT_GLYPH_COUNT {len(glyphs)}")
    out.append("static const fe_glyph_def FE_FONT_GLYPHS[FE_FONT_GLYPH_COUNT] = {")
    for ch, gx, gy, gw, gh, adv, left in glyphs:
        out.append(f"    {{ {gx}, {gy}, {gw}, {gh}, {adv:.3f}f, {left - pad} }},")
    out.append("};")
    out.append(f"static const unsigned int FE_FONT_Z_SIZE = {len(data)}u;")
    out.append("static const uint8_t FE_FONT_Z[] = {")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    out.append("};\n#endif")
    a.out.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"{a.out}: atlas {width}x{height}, {len(data)} bytes deflated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
