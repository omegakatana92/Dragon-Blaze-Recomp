"""Generate runtime/src/sh2_interp.c: an SH-2 interpreter used as a fallback
for code the static translator did not reach.

The interpreter is built from the same decoder (tools/sh2dec.py) and the same
semantic functions (runtime/src/sh2_ops.c) as the translated program, so an
instruction behaves identically whichever path executes it, including cycle
counts and delay-slot handling.  The output contains no ROM data.

usage: python tools/make_sh2_interp.py [--out runtime/src/sh2_interp.c]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import sh2dec as D

ROOT = Path(__file__).resolve().parent.parent

KINDS = [D.OP, D.PCREL, D.LDCSR, D.BT, D.BF, D.BTS, D.BFS, D.BRA, D.BSR, D.BRAF, D.BSRF,
         D.JMP, D.JSR, D.RTS, D.RTE, D.TRAPA, D.SLEEP, D.ILLEGAL]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "runtime" / "src" / "sh2_interp.c")
    args = ap.parse_args()

    names: dict[str, int] = {}
    arity: dict[str, int] = {}
    rows = []
    for op in range(0x10000):
        ins = D.decode(op, 0x1000)
        k = KINDS.index(ins.kind)
        nm = 0
        a = list(ins.args) + [0, 0, 0]
        disp = 0
        if ins.kind in (D.OP, D.PCREL, D.LDCSR):
            if ins.name not in names:
                names[ins.name] = len(names) + 1
                arity[ins.name] = len(ins.args)
            nm = names[ins.name]
        if ins.target is not None:
            disp = ((ins.target - 0x1000 - 4) & 0xFFFFFFFF)
            if disp & 0x80000000:
                disp -= 1 << 32
            disp //= 2
        rows.append(f"{{{k},{nm},{a[0]},{a[1]},{a[2]},{disp}}}")

    L = ["/* Generated by tools/make_sh2_interp.py -- do not edit.",
         " * SH-2 fallback interpreter: same decoder and semantic functions as the",
         " * translated program (see tools/recompilesh2.py emit()), cycles added in the same order. */",
         '#include "sh2/sh2.h"', "",
         "enum { " + ", ".join(f"K_{k.upper()}" for k in KINDS) + " };", "",
         "typedef struct { uint8_t kind, name, a0, a1, a2; int16_t disp; } dec_t;", "",
         "static const dec_t T[65536] = {"]
    for i in range(0, 65536, 8):
        L.append("    " + ",".join(rows[i:i + 8]) + ",")
    L += ["};", "",
          "/* runs a non-branch instruction; returns 0 if it is not one */",
          "static int body(sh2_state *s, const dec_t *d, uint32_t pc_value)",
          "{",
          "    if (d->kind == K_PCREL) s->pc = pc_value;",
          "    switch (d->name) {"]
    for nm, idx in names.items():
        call = ", ".join(["s"] + [f"d->a{j}" for j in range(arity[nm])])
        L.append(f"    case {idx}: sh2_{nm}({call}); return 1;")
    L += ["    default: return 0;", "    }", "}", "",
          "uint32_t sh2_interp_step(sh2_state *s, uint32_t a)",
          "{",
          "    const dec_t *d = &T[sh2_rd16(a)];",
          "    uint32_t nxt = a + 2u, tgt;",
          "    switch (d->kind) {",
          "    case K_OP: case K_PCREL: case K_LDCSR: body(s, d, nxt); s->cycles += 1; return nxt;",
          "    case K_SLEEP: s->cycles += 1; return sh2_sleep(s, a);",
          "    case K_ILLEGAL: tgt = sh2_illegal(s, a); s->cycles += 1; return tgt;",
          "    case K_TRAPA: tgt = sh2_trapa(s, d->a0, nxt); s->cycles += 1; return tgt;",
          "    case K_BT: s->cycles += 1; if (s->sr & SH_T) { s->cycles += 2; return a + 4u + (uint32_t)(d->disp * 2); } return nxt;",
          "    case K_BF: s->cycles += 1; if (!(s->sr & SH_T)) { s->cycles += 2; return a + 4u + (uint32_t)(d->disp * 2); } return nxt;",
          "    default: break;",
          "    }",
          "    /* delayed branches */",
          "    const dec_t *sd = &T[sh2_rd16(a + 2u)];",
          "    int k = d->kind;",
          "    if (k == K_BTS || k == K_BFS) {",
          "        int c = (s->sr & SH_T) != 0;",
          "        if (k == K_BFS) c = !c;",
          "        s->cycles += 1;",
          "        if (!c) return nxt;",
          "        s->cycles += 1;",
          "        tgt = a + 4u + (uint32_t)(d->disp * 2);",
          "    } else {",
          "        switch (k) {",
          "        case K_BRA: s->cycles += 2; tgt = a + 4u + (uint32_t)(d->disp * 2); break;",
          "        case K_BSR: s->cycles += 2; s->pr = a + 4u; tgt = a + 4u + (uint32_t)(d->disp * 2); break;",
          "        case K_BRAF: tgt = a + 4u + s->r[d->a0]; s->cycles += 2; break;",
          "        case K_BSRF: tgt = a + 4u + s->r[d->a0]; s->pr = a + 4u; s->cycles += 2; break;",
          "        case K_JMP: tgt = s->r[d->a0]; s->cycles += 1; break;",
          "        case K_JSR: tgt = s->r[d->a0]; s->pr = a + 4u; s->cycles += 2; break;",
          "        case K_RTS: tgt = s->pr; s->cycles += 2; break;",
          "        case K_RTE: tgt = sh2_rte_pop(s); s->cycles += 1; break;",
          "        default: return sh2_unsupported(s, a);",
          "        }",
          "    }",
          "    if (!body(s, sd, a + 4u)) return sh2_illegal(s, a + 2u);",
          "    s->cycles += 1;   /* delay slot */",
          "    return tgt;",
          "}", ""]
    args.out.write_text("\n".join(L), encoding="ascii")
    print(f"{args.out}: {len(names)} semantic functions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
